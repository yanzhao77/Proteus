from typing import Any, Mapping, Protocol


class EntryDraftApi(Protocol):
    def create(self, creator_subject: str, **kwargs: Any) -> Mapping[str, Any]: ...
    def revise(self, creator_subject: str, draft_id: str, **kwargs: Any) -> Mapping[str, Any]: ...
    def submit(self, creator_subject: str, draft_id: str, **kwargs: Any) -> Mapping[str, Any]: ...
    def archive(self, creator_subject: str, draft_id: str, **kwargs: Any) -> Mapping[str, Any]: ...
    def list(self, creator_subject: str) -> Mapping[str, Any]: ...
    def get(self, creator_subject: str, draft_id: str) -> Mapping[str, Any]: ...


class UnavailableEntryDraftApi:
    def _unavailable(self, *_args: Any, **_kwargs: Any) -> Mapping[str, Any]:
        return {"availability": "NOT_AVAILABLE", "reason": "ENTRY_DRAFT_AUTHORITY_UNAVAILABLE", "items": [], "item": None}
    create = revise = submit = archive = list = get = _unavailable
